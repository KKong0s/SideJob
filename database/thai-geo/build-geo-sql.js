// Builds geo.sql from the kongvut/thai-province-data raw files in this folder.
// Source: https://github.com/kongvut/thai-province-data (MIT, see LICENSE)
// Usage: node build-geo-sql.js
//
// The source uses 6 regions; SideJob groups provinces into the 4-region scheme:
//   north (17 provinces), central incl. east & west (26), northeast (20), south (14).

const fs = require('fs');
const path = require('path');

const load = (name) => JSON.parse(fs.readFileSync(path.join(__dirname, `${name}.json`), 'utf8'));
const provinces = load('provinces').filter((p) => !p.deleted_at);
const districts = load('districts').filter((d) => !d.deleted_at);

const REGIONS = [
  { id: 1, th: 'ภาคเหนือ', en: 'Northern' },
  { id: 2, th: 'ภาคกลาง', en: 'Central' },
  { id: 3, th: 'ภาคตะวันออกเฉียงเหนือ', en: 'Northeastern' },
  { id: 4, th: 'ภาคใต้', en: 'Southern' },
];

// Source geography id -> SideJob region id
const GEOGRAPHY_TO_REGION = { 1: 1, 2: 2, 3: 3, 4: 2, 5: 2, 6: 4 };

// Lower-north provinces that the 6-region scheme puts in Central/Western
const LOWER_NORTH_PROVINCE_IDS = new Set([
  47, // นครสวรรค์
  48, // อุทัยธานี
  49, // กำแพงเพชร
  50, // ตาก
  51, // สุโขทัย
  52, // พิษณุโลก
  53, // พิจิตร
  54, // เพชรบูรณ์
]);

const EXPECTED_COUNTS = { 1: 17, 2: 26, 3: 20, 4: 14 };

const regionOf = (p) => (LOWER_NORTH_PROVINCE_IDS.has(p.id) ? 1 : GEOGRAPHY_TO_REGION[p.geography_id]);
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;

// Sanity checks so a changed upstream file fails loudly instead of silently
if (provinces.length !== 77) throw new Error(`Expected 77 provinces, got ${provinces.length}`);
for (const [regionId, expected] of Object.entries(EXPECTED_COUNTS)) {
  const actual = provinces.filter((p) => regionOf(p) === Number(regionId)).length;
  if (actual !== expected) throw new Error(`Region ${regionId}: expected ${expected} provinces, got ${actual}`);
}
const provinceIds = new Set(provinces.map((p) => p.id));
for (const d of districts) {
  if (!provinceIds.has(d.province_id)) throw new Error(`District ${d.id} has unknown province ${d.province_id}`);
}

const chunk = (rows, size) => Array.from({ length: Math.ceil(rows.length / size) }, (_, i) => rows.slice(i * size, (i + 1) * size));

const lines = [
  '-- Generated by database/thai-geo/build-geo-sql.js. Do not edit by hand.',
  '-- Source: kongvut/thai-province-data (MIT)',
  'SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;',
  'USE sidejob;',
  '',
  'INSERT INTO regions (id, name_th, name_en) VALUES',
  REGIONS.map((r) => `  (${r.id}, ${q(r.th)}, ${q(r.en)})`).join(',\n') + ';',
  '',
  'INSERT INTO provinces (id, region_id, name_th, name_en) VALUES',
  provinces.map((p) => `  (${p.id}, ${regionOf(p)}, ${q(p.name.th)}, ${q(p.name.en)})`).join(',\n') + ';',
  '',
];

for (const rows of chunk(districts, 200)) {
  lines.push('INSERT INTO districts (id, province_id, name_th, name_en) VALUES');
  lines.push(rows.map((d) => `  (${d.id}, ${d.province_id}, ${q(d.name.th)}, ${q(d.name.en)})`).join(',\n') + ';');
  lines.push('');
}

fs.writeFileSync(path.join(__dirname, 'geo.sql'), lines.join('\n'), 'utf8');
console.log(`geo.sql: ${REGIONS.length} regions, ${provinces.length} provinces, ${districts.length} districts`);
